// Command speccov writes spec/coverage.md: every RPC method in the spec, the
// phase that owns it (spec/phases.tsv), whether yatt-server implements it,
// and which conformance scenarios call it.
//
//	go run ./cmd/speccov            # from server/, rewrites ../spec/coverage.md
//	go run ./cmd/speccov -check     # fails if coverage.md is out of date
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/jadewisemann/yet-another-t3-code/server/internal/conform"
	"github.com/jadewisemann/yet-another-t3-code/server/internal/server"
	"github.com/jadewisemann/yet-another-t3-code/server/internal/spec"
)

func main() {
	root := flag.String("root", "..", "repository root")
	check := flag.Bool("check", false, "fail instead of writing when coverage.md is stale")
	flag.Parse()
	sp, err := spec.Load(filepath.Join(*root, "spec/generated/rpc.json"))
	must(err)
	phases := loadPhases(filepath.Join(*root, "spec/phases.tsv"))
	scenarios, err := conform.LoadScenarios(filepath.Join(*root, "conformance/scenarios"), nil)
	must(err)
	golden := map[string]bool{}
	byMethod := map[string][]string{}
	for _, sc := range scenarios {
		if _, err := os.Stat(filepath.Join(*root, "conformance/golden", sc.Name+".json")); err == nil {
			golden[sc.Name] = true
		}
		seen := map[string]bool{}
		for _, st := range sc.Steps {
			if st.Method != "" && !seen[st.Method] {
				seen[st.Method] = true
				byMethod[st.Method] = append(byMethod[st.Method], sc.Name)
			}
		}
	}
	impl := map[string]bool{}
	for _, m := range server.ImplementedMethods() {
		impl[m] = true
	}

	type row struct{ method, kind, phase, done, tests string }
	var rows []row
	type tally struct{ total, done, tested int }
	perPhase := map[string]*tally{}
	for _, m := range sp.MethodNames() {
		ph := phaseOf(phases, m)
		if perPhase[ph] == nil {
			perPhase[ph] = &tally{}
		}
		t := perPhase[ph]
		t.total++
		done := ""
		if impl[m] {
			done = "yes"
			t.done++
		}
		if len(byMethod[m]) > 0 {
			t.tested++
		}
		rows = append(rows, row{m, sp.Methods[m].Kind, ph, done, strings.Join(byMethod[m], ", ")})
	}
	sort.SliceStable(rows, func(i, j int) bool { return rows[i].phase < rows[j].phase })

	var b bytes.Buffer
	fmt.Fprintf(&b, "# RPC coverage\n\nGenerated by `go run ./cmd/speccov` from `spec/generated/rpc.json` (upstream %s, %s). Do not edit by hand.\n\n",
		sp.Upstream.Tag, sp.Upstream.Commit[:10])
	fmt.Fprintf(&b, "| Phase | Methods | Implemented | Covered by a scenario |\n|---|---|---|---|\n")
	var names []string
	for ph := range perPhase {
		names = append(names, ph)
	}
	sort.Strings(names)
	for _, ph := range names {
		t := perPhase[ph]
		fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", ph, t.total, t.done, t.tested)
	}
	fmt.Fprintf(&b, "\n| Method | Kind | Phase | Implemented | Scenarios |\n|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", r.method, r.kind, r.phase, r.done, r.tests)
	}
	var unknown []string
	for m := range byMethod {
		if _, ok := sp.Methods[m]; !ok {
			unknown = append(unknown, m)
		}
	}
	sort.Strings(unknown)
	if len(unknown) > 0 {
		fmt.Fprintf(&b, "\nScenarios also call methods outside the spec on purpose: %s.\n", "`"+strings.Join(unknown, "`, `")+"`")
	}
	out := filepath.Join(*root, "spec/coverage.md")
	if *check {
		old, _ := os.ReadFile(out)
		if !bytes.Equal(old, b.Bytes()) {
			fmt.Fprintln(os.Stderr, "spec/coverage.md is out of date; run `go run ./cmd/speccov` in server/")
			os.Exit(1)
		}
		return
	}
	must(os.WriteFile(out, b.Bytes(), 0o644))
}

type phaseRule struct {
	re    *regexp.Regexp
	phase string
}

func loadPhases(path string) []phaseRule {
	data, err := os.ReadFile(path)
	must(err)
	var rules []phaseRule
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, "pattern") {
			continue
		}
		f := strings.Fields(line)
		pat := "^" + strings.ReplaceAll(regexp.QuoteMeta(f[0]), `\*`, ".*") + "$"
		rules = append(rules, phaseRule{regexp.MustCompile(pat), f[1]})
	}
	return rules
}

func phaseOf(rules []phaseRule, m string) string {
	for _, r := range rules {
		if r.re.MatchString(m) {
			return r.phase
		}
	}
	return "?"
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
